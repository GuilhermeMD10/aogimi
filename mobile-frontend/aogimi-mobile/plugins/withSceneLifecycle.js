// Adopt the UIScene lifecycle on iOS.
//
// An app built with the iOS 27 SDK (Xcode 27) that still uses the app-delegate
// window traps at launch in UIKit (`_UIApplicationEvaluateRuntimeIssueForNoScene
// LifecycleAdoption`) — Apple's deadline for the scene migration. Expo SDK 55's
// template predates it, so prebuild emits an AppDelegate that owns the window.
//
// Three mods, together the whole migration:
//   - Info.plist gets a UIApplicationSceneManifest naming SceneDelegate.
//   - SceneDelegate.swift is written next to AppDelegate.swift and added to the
//     target. It creates the window on its UIWindowScene and starts React Native
//     there; URL opens and universal links arrive on the scene now, so it
//     forwards them to the AppDelegate's existing handlers.
//   - AppDelegate stops creating the window — it still builds the factory,
//     which SceneDelegate borrows.
//
// Delete this plugin once Expo's template adopts scenes itself.

const fs = require("fs");
const path = require("path");
const { withAppDelegate, withDangerousMod, withInfoPlist, withXcodeProject, IOSConfig } = require("expo/config-plugins");

const SCENE_DELEGATE = `import UIKit
import React

// Generated by plugins/withSceneLifecycle.js — edit there, not here.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene,
          let appDelegate = UIApplication.shared.delegate as? AppDelegate,
          let factory = appDelegate.reactNativeFactory else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // A cold start from a link carries the URL here, not in launchOptions;
    // hand it over where Linking.getInitialURL looks for it.
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    guard let url = URLContexts.first?.url else { return }
    _ = UIApplication.shared.delegate?.application?(UIApplication.shared, open: url, options: [:])
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = UIApplication.shared.delegate?.application?(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const WINDOW_BLOCK = /#if os\(iOS\) \|\| os\(tvOS\)\n\s*window = UIWindow\(frame: UIScreen\.main\.bounds\)[\s\S]*?#endif\n/;
const WINDOW_MOVED = "    // The window is created by SceneDelegate (plugins/withSceneLifecycle.js).\n";

function withSceneManifest(config) {
  return withInfoPlist(config, (cfg) => {
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: "Default Configuration",
            UISceneDelegateClassName: "$(PRODUCT_MODULE_NAME).SceneDelegate",
          },
        ],
      },
    };
    return cfg;
  });
}

function withSceneDelegateFile(config) {
  config = withDangerousMod(config, [
    "ios",
    (cfg) => {
      const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
      const file = path.join(cfg.modRequest.platformProjectRoot, projectName, "SceneDelegate.swift");
      fs.writeFileSync(file, SCENE_DELEGATE);
      return cfg;
    },
  ]);
  return withXcodeProject(config, (cfg) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(cfg.modRequest.projectRoot);
    const filepath = `${projectName}/SceneDelegate.swift`;
    if (!cfg.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({ filepath, groupName: projectName, project: cfg.modResults });
    }
    return cfg;
  });
}

function withoutAppDelegateWindow(config) {
  return withAppDelegate(config, (cfg) => {
    const { contents } = cfg.modResults;
    if (contents.includes(WINDOW_MOVED)) return cfg;
    if (!WINDOW_BLOCK.test(contents)) {
      throw new Error("withSceneLifecycle: AppDelegate window block not found — the Expo template changed; revisit this plugin.");
    }
    cfg.modResults.contents = contents.replace(WINDOW_BLOCK, WINDOW_MOVED);
    return cfg;
  });
}

module.exports = (config) => withoutAppDelegateWindow(withSceneDelegateFile(withSceneManifest(config)));
